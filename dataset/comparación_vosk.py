from vosk import Model, KaldiRecognizer
from pydub import AudioSegment

# ==========================================
# 2. DESCARGA DEL MODELO VOSK (ESPAÑOL)
# ==========================================
model_dir = "vosk-model-small-es-0.42"
model_zip = "vosk-model-es.zip"
url_modelo = "https://alphacephei.com/vosk/models/vosk-model-small-es-0.42.zip"

if not os.path.exists(model_dir):
    print("📥 Descargando el modelo pequeño de Vosk en español...")
    urllib.request.urlretrieve(url_modelo, model_zip)
    print("📦 Descomprimiendo el modelo...")
    with zipfile.ZipFile(model_zip, "r") as zip_ref:
        zip_ref.extractall(".")
    os.remove(model_zip)

print("✅ Modelo cargado correctamente.")
model = Model(model_dir)

# ==========================================
# 3. FUNCIÓN DE TRANSCRIPCIÓN
# ==========================================
def transcribir_audio(ruta_audio):
    try:
        # Convertir cualquier formato (ogg, mp3, etc.) a WAV 16kHz Mono PCM
        sound = AudioSegment.from_file(ruta_audio)
        sound = sound.set_frame_rate(16000).set_channels(1).set_sample_width(2)
        temp_wav = "temp_process.wav"
        sound.export(temp_wav, format="wav")

        # Procesar con Vosk
        wf = wave.open(temp_wav, "rb")
        rec = KaldiRecognizer(model, wf.getframerate())
        rec.SetWords(True)

        texto_fragmentos = []
        while True:
            data = wf.readframes(4000)
            if len(data) == 0:
                break
            if rec.AcceptWaveform(data):
                res = json.loads(rec.Result())
                if res.get("text"):
                    texto_fragmentos.append(res["text"])

        res_final = json.loads(rec.FinalResult())
        if res_final.get("text"):
            texto_fragmentos.append(res_final["text"])

        wf.close()
        if os.path.exists(temp_wav):
            os.remove(temp_wav)

        return " ".join(texto_fragmentos)
    except Exception as e:
        print(f"⚠️ Error al procesar {os.path.basename(ruta_audio)}: {e}")
        return ""

# ==========================================
# 4. BUSCAR AUDIOS EN LA CARPETA 'Audios'
# ==========================================
# Buscar la carpeta Audios en Drive (busca la primera coincidencia que encuentre)
print("🔍 Buscando la carpeta 'Audios' en tu Drive...")
carpeta_audios = None
for root, dirs, files in os.walk('/content/drive/MyDrive'):
    if 'Audios' in dirs:
        carpeta_audios = os.path.join(root, 'Audios')
        break

if not carpeta_audios:
    # Ruta por defecto si está en la raíz de Drive
    carpeta_audios = '/content/drive/MyDrive/Audios'

print(f"📂 Carpeta detectada: {carpeta_audios}")

# Obtener todos los archivos de audio de la carpeta
extensiones = ('*.ogg', '*.wav', '*.mp3', '*.m4a', '*.OPUS', '*.OGG')
archivos_audio = []
for ext in extensiones:
    archivos_audio.extend(glob.glob(os.path.join(carpeta_audios, ext)))

# Ordenar archivos alfabéticamente
archivos_audio = sorted(archivos_audio)
total_audios = len(archivos_audio)

print(f"🎙️ Se encontraron {total_audios} archivos de audio.")

# ==========================================
# 5. PROCESAMIENTO EN LOTE Y GUARDADO EN CSV
# ==========================================
resultados = []

for idx, ruta_file in enumerate(archivos_audio, 1):
    nombre_archivo = os.path.basename(ruta_file)
    print(f"[{idx}/{total_audios}] Transcribiendo: {nombre_archivo}...")

    transcripcion = transcribir_audio(ruta_file)
    resultados.append({
        "Audio obtenido": nombre_archivo,
        "Texto obtenido por modelo (Vosk)": transcripcion
    })

# Convertir a DataFrame y guardar CSV en la carpeta Audios
df_resultados = pd.DataFrame(resultados)
ruta_csv = os.path.join(carpeta_audios, "resultados_vosk.csv")
df_resultados.to_csv(ruta_csv, index=False, encoding="utf-8-sig")

print("\n🎉 ¡PROCESO FINALIZADO CON ÉXITO!")
print(f"📄 El archivo de resultados fue guardado en: {ruta_csv}")

